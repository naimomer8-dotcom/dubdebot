export function scoreDisc(answers: Record<string, string>) {
  const c: Record<Disc, number> = { D: 0, I: 0, S: 0, C: 0 };
  for (const v of Object.values(answers)) if (v in c) c[v as Disc]++;
  const total = Object.values(c).reduce((a, b) => a + b, 0) || 1;
  const pct = Object.fromEntries(Object.entries(c).map(([k, v]) => [k, Math.round((v / total) * 100)])) as Record<Disc, number>;
  const order = (Object.keys(c) as Disc[]).sort((a, b) => c[b] - c[a]);
  return { pct, main: order[0], second: order[1] };
}

